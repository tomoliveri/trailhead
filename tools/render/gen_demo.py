#!/usr/bin/env python3
"""Real Trailhead plan for a sample runner -> Monkey C data for the watch demo build (DemoData.mc)."""
import datetime as dt
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'web', 'py'))
import trailhead as T  # noqa: E402

TODAY = dt.date.today()
prof = {'athlete': {'name': 'Sam', 'age': 36, 'hr_max': 188, 'hr_rest': 52},
        'race': {'name': 'Sydney', 'date': (TODAY + dt.timedelta(weeks=14)).isoformat(), 'goal_min': 225},
        'recent': {'race_km': 10, 'race_min': 47.5, 'date': (TODAY - dt.timedelta(days=12)).isoformat()},
        'current': {'runs_per_week': 5, 'easy_min': 45, 'long_min': 110, 'weeks_running': 8},
        'availability': {'mon': {'primary': 0}, 'tue': {'primary': 70, 'total': 90}, 'wed': {'primary': 50},
                         'thu': {'primary': 70, 'total': 90}, 'fri': {'primary': 0}, 'sat': {'primary': 180},
                         'sun': {'primary': 60}}}
st = T.new_state(prof, TODAY)
out = T.refresh(st, TODAY)
b = out['bundle']
# today = the first day with a structured run session (intervals or long run)
pick = next((d for d in out['days'] if d['kind'] in ('long_mp', 'vo2', 'threshold', 'long') and d.get('steps')), out['days'][0])
sync = dict(b[pick['date']])
sync['now'] = 0
sync['today'] = dict(sync['today'], date=TODAY.isoformat())
sync['rd'] = 82
sync['done'] = False
sync['km_d'] = 21.4
sync.pop('preview', None)
for t in sync.get('tasks', []):
    t.pop('want', None)
for i, w in enumerate(sync['wk']):
    w['d'] = 1 if i < 2 else (2 if i == 2 else 0)


def mc(v):
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(round(v, 3)) if v != int(v) else f'{int(v)}.0'
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return '[' + ', '.join(mc(x) for x in v) + '] as Array'
    if isinstance(v, dict):
        return '{' + ', '.join(f'{json.dumps(str(k), ensure_ascii=False)} => {mc(x)}' for k, x in v.items()) + '} as Dictionary'
    raise TypeError(type(v))


steps = sync['today']['s']
src = f"""import Toybox.Lang;

//! Generated by tools/render/gen_demo.py from a real Trailhead plan ({pick['date']}: {pick['title']}).
module DemoData {{
    function sync() as Dictionary {{
        return {mc(sync)};
    }}
}}
"""
open(sys.argv[1] if len(sys.argv) > 1 else 'DemoData.mc', 'w').write(src)
print('today:', pick['date'], pick['title'], len(steps), 'steps; race', sync['race'], 'cd', sync['cd'])
